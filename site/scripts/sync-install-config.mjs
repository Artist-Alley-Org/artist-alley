#!/usr/bin/env node
// Parse docs/install/config/aa.env.example into a Starlight-friendly
// MDX partial that install.mdx imports. Single source of truth for
// the env-var reference table.
//
// Output: site/src/content/_partials/install-config-table.mdx
//
// The example file uses these conventions:
//   * Comments above a variable describe it (paragraphs).
//   * Section headers look like `# ── Section name ──...`.
//   * `KEY="value"` or `KEY=value` declares a default.
//   * `#KEY="..."` (commented) means "optional / not set by default".
//
// Variables marked `(required)` in a comment override the default.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const SRC = resolve(ROOT, "docs", "install", "config", "aa.env.example");
const OUT = resolve(HERE, "..", "src", "content", "_partials", "install-config-table.mdx");

const raw = readFileSync(SRC, "utf8");

// ── Parse the env file. Build a list of sections, each with its
// own variable rows. A "section" is delimited by a `# ── Name ──`
// banner. Inside a section, blocks of comment lines followed by a
// variable line form one entry.

const sections = [];
let currentSection = null;
let commentBuffer = [];

function flushSection() {
  if (currentSection && currentSection.rows.length > 0) {
    sections.push(currentSection);
  }
}

for (const line of raw.split("\n")) {
  const t = line.trim();

  if (!t) {
    // Blank line ends a comment block.
    commentBuffer = [];
    continue;
  }

  // Section banner: `# ── Name ──...` or `# ── Name ─────`.
  const bannerMatch = t.match(/^#\s*──\s*(.+?)\s*─/);
  if (bannerMatch) {
    flushSection();
    currentSection = { title: bannerMatch[1], rows: [] };
    commentBuffer = [];
    continue;
  }

  // Plain comment — accumulate as description for the next var.
  if (t.startsWith("#")) {
    const body = t.replace(/^#+\s?/, "").trim();
    // Skip block separators "─────" and similar.
    if (body && !/^[─=*-]+$/.test(body)) {
      commentBuffer.push(body);
    }
    continue;
  }

  // Variable assignment.
  const varMatch = line.match(/^(#?)\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*)$/);
  if (varMatch) {
    const [, hash, name, rawVal] = varMatch;
    const commented = hash === "#";
    const value = rawVal.trim().replace(/^"(.*)"$/, "$1");

    // Description is the immediately-preceding comment block.
    const description = commentBuffer.join(" ").trim();
    const required = /\(required\)/i.test(description);

    if (!currentSection) {
      currentSection = { title: "General", rows: [] };
    }
    currentSection.rows.push({
      name,
      value,
      commented,
      required,
      description,
    });
    commentBuffer = [];
    continue;
  }
}
flushSection();

// ── Emit a Starlight-friendly MDX table per section.

function esc(s) {
  return s
    .replace(/\|/g, "\\|")
    .replace(/</g, "\\<")
    .replace(/>/g, "\\>");
}

const lines = [];
lines.push("{/* AUTO-GENERATED by site/scripts/sync-install-config.mjs.");
lines.push("    Source: docs/install/config/aa.env.example.");
lines.push("    DO NOT EDIT — re-run `pnpm prebuild` after changing the source. */}");
lines.push("");

for (const section of sections) {
  lines.push(`### ${section.title}`);
  lines.push("");
  lines.push("| Variable | Default | Notes |");
  lines.push("|----------|---------|-------|");
  for (const row of section.rows) {
    const defaultCell = row.commented
      ? "_unset_"
      : row.required
        ? "**required**"
        : row.value === ""
          ? "_empty_"
          : `\`${row.value}\``;
    const notes = esc(row.description);
    lines.push(`| \`${row.name}\` | ${defaultCell} | ${notes} |`);
  }
  lines.push("");
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
console.log(
  `[sync-install-config] wrote ${OUT.replace(ROOT + "/", "")} ` +
    `(${sections.length} section(s), ${sections.reduce((a, s) => a + s.rows.length, 0)} variable(s))`,
);
