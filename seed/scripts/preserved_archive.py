# The roots the archive is authoritative for. `local` is the measured
# case: no media_url, no source_archive, and the source tree is gone.
PRESERVED_ROOTS = frozenset({"local"})

CSV_NAME = "metadata.csv"
GROUPS_NAME = "groups.csv"

TRANSFORM_KIND = "metadata-csv-transform"
TRANSFORM_VERSION = 1
SNAPSHOT_KIND = "frozen-snapshot-manifest"

FILE_PATH_COLUMN = "file_path"

_SHA256_HEX = 64


class PreservedError(ValueError):
    """The contract cannot be used, so nothing may proceed.

    Raised, never returned, for the reason `CollapseError` is: an
    unusable document must never quietly become "no expectations". That
    reading is what let a header-only `metadata.csv` publish in silence.
    """


# ---------------------------------------------------------------------------
# 1. Alias refusal
# ---------------------------------------------------------------------------

def _resolved(p: Path | str) -> Path:
    return Path(p).expanduser().resolve()


def _contains(outer: Path, inner: Path) -> bool:
    """`inner` is at or below `outer`, on resolved paths only.

    `is_relative_to` rather than a string prefix: `/a/bc` starts with
    `/a/b` as text and is not inside it, and `..` plus a symlink defeat
    prefix matching in both directions.
    """
    return inner == outer or inner.is_relative_to(outer)


def alias_refusals(paths: Mapping[str, Path | str | None], *,
                   equal_ok_within: Iterable[Iterable[str]] = ()) -> list[str]:
    """Every pair of supplied paths that are the same tree, or nested.

    ⛔ THIS RUNS BEFORE ANY MUTATION AND BEFORE ANY EVIDENCE IS USED. A
    source root that IS the destination makes the destination its own
    evidence, which is the exact failure ADR 0097 exists to prevent, and
    nesting is the same defect: a "source" holding the destination inside
    it reads bytes this run is about to write.

    Every path the caller knows about is passed in, labelled, including
    the frozen snapshot, the evidence documents and the scratch
    directories. A pair missing from the map is a pair nobody checked.
    """
    groups = [frozenset(g) for g in equal_ok_within]
    named = [(label, _resolved(p)) for label, p in paths.items() if p is not None]
    out: list[str] = []
    for i, (la, a) in enumerate(named):
        for lb, b in named[i + 1:]:
            if a == b:
                # ⚠️ TWO READ-ONLY SOURCE ROOTS MAY BE ONE TREE, and that is
                # the only exemption. A single dataset root serving both
                # `local` and `internet` reads the same bytes twice and
                # writes nothing, so it is a configuration rather than a
                # defect. Nesting is still refused even inside a group, and
                # nothing is ever exempted from the comparison against the
                # tree this run WRITES.
                if any(la in g and lb in g for g in groups):
                    continue
                out.append(f"{la} and {lb} are the same path ({a}); one of them "
                           f"would be its own evidence")
            elif _contains(a, b):
                out.append(f"{la} ({a}) CONTAINS {lb} ({b}); reading through one "
                           f"would read bytes the other writes")
            elif _contains(b, a):
                out.append(f"{lb} ({b}) CONTAINS {la} ({a}); reading through one "
                           f"would read bytes the other writes")
    return out


def refuse_aliasing(paths: Mapping[str, Path | str | None], *,
                    equal_ok_within: Iterable[Iterable[str]] = (),
                    stream=None) -> bool:
    """Print and return False on any aliasing; True when the set is clean.

    ⚠️ `stream` defaults to None and is resolved at CALL time. A
    `stream=sys.stderr` default is bound once, at import, so a caller that
    redirects stderr would not see the refusal, and a refusal nobody can
    read is a refusal nobody can act on.
    """
    stream = stream or sys.stderr
    bad = alias_refusals(paths, equal_ok_within=equal_ok_within)
    if not bad:
        return True
    print(f"error: {len(bad)} path aliasing refusal(s):", file=stream)
    for b in bad:
        print(f"  - {b}", file=stream)
    print("  Refusing. Source and destination must be distinct trees: the "
          "published archive is the thing being written, so it cannot also be "
          "the thing being read as authority.", file=stream)
    return False


# ---------------------------------------------------------------------------
# 2. The metadata.csv expected-transform contract
# ---------------------------------------------------------------------------

def split_csv_records(blob: bytes) -> tuple[bytes, list[bytes]]:
    """(header bytes, data record bytes), every record keeping its own
    terminator so the concatenation is the original file exactly.

    A record ends at a newline that is not inside a quoted field. See the
    module docstring: site_b's published CSV carries bare LFs inside
    quoted values, and a parse-and-rewrite would not give them back.
    """
    records: list[bytes] = []
    start = 0
    in_quote = False
    for i, byte in enumerate(blob):
        if byte == 0x22:            # "
            in_quote = not in_quote
        elif byte == 0x0A and not in_quote:
            records.append(blob[start:i + 1])
            start = i + 1
    if start < len(blob):
        records.append(blob[start:])
    if not records:
        raise PreservedError("the CSV is empty: there is not even a header row")
    if in_quote:
        raise PreservedError("the CSV ends inside a quoted field; it is truncated "
                             "and cannot be filtered safely")
    return records[0], records[1:]


def record_fields(record: bytes) -> list[str]:
    """The parsed fields of one raw record. Parsing is for READING a
    column; the bytes themselves are never re-emitted from here."""
    text = record.decode("utf-8")
    rows = list(csv.reader(io.StringIO(text)))
    return rows[0] if rows else []


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def ordered_digest(row_digests: Iterable[str]) -> str:
    """Order-sensitive digest over the retained rows.

    ⛔ ORDER IS PART OF THE CLAIM. A digest over a SET would accept a
    reordered file, and a reordered `metadata.csv` is a changed published
    artifact whatever its multiset of rows says.
    """
    h = hashlib.sha256()
    for d in row_digests:
        h.update(bytes.fromhex(d))
    return h.hexdigest()


def _file_path_index(header: bytes) -> tuple[list[str], int]:
    fields = record_fields(header)
    if FILE_PATH_COLUMN not in fields:
        raise PreservedError(
            f"the CSV header has no {FILE_PATH_COLUMN!r} column, so a row cannot "
            f"be tied to a retired record. Header: {fields}")
    return fields, fields.index(FILE_PATH_COLUMN)


def read_csv(path: Path) -> tuple[bytes, bytes, list[bytes], list[str], int]:
    """(blob, header, rows, header_fields, file_path column index)."""
    try:
        blob = path.read_bytes()
    except OSError as e:
        raise PreservedError(f"{path}: unreadable ({e})") from e
    header, rows = split_csv_records(blob)
    fields, idx = _file_path_index(header)
    return blob, header, rows, fields, idx


def build_csv_transform(csv_path: Path, *,
                        removals: Iterable[tuple[str, str]],
                        site: Path | None = None) -> dict:
    """The expected-transform document, from the PRE-OPERATION CSV.

    `removals` is (file_path, retired_id) pairs, taken from the committed
    collapse document. A retirement whose `retired_file_path` has no row
    here contributes no removal, which is how site_a's ZERO-REMOVAL
    transform arises: its `metadata.csv` must stay byte-identical, 907
    rows to 907, and that is an expectation to enforce rather than a case
    to skip.
    """
    blob, header, rows, fields, idx = read_csv(csv_path)

    # ⛔ CARDINALITY BEFORE KEYING ON IT. The removals are keyed by
    # `file_path`, so a duplicated one would make "the row this retired
    # record names" ambiguous and could drop a row nobody enumerated.
    seen: dict[str, int] = {}
    for row in rows:
        f = record_fields(row)
        if len(f) <= idx:
            raise PreservedError(
                f"{csv_path}: a data row has {len(f)} field(s), fewer than the "
                f"{len(fields)}-field header reaches; the file is malformed")
        seen[f[idx]] = seen.get(f[idx], 0) + 1
    dupes = sorted(k for k, n in seen.items() if n > 1)
    if dupes:
        raise PreservedError(
            f"{csv_path}: {len(dupes)} {FILE_PATH_COLUMN} value(s) appear on more "
            f"than one row ({dupes[:5]}). A removal is keyed on this column, so a "
            f"duplicate makes the row a retirement names ambiguous.")

    wanted: dict[str, str] = {}
    for file_path, retired_id in removals:
        if file_path in wanted:
            raise PreservedError(
                f"two retirements name the same row {file_path!r} "
                f"({wanted[file_path]} and {retired_id})")
        if file_path not in seen:
            # Not an error: an `hq` retirement whose produced render has
            # no CSV row is the ordinary case. Recorded nowhere, removed
            # nowhere.
            continue
        wanted[file_path] = retired_id

    retained: list[bytes] = []
    removed: list[dict] = []
    for row in rows:
        fp = record_fields(row)[idx]
        rid = wanted.get(fp)
        if rid is not None:
            removed.append({FILE_PATH_COLUMN: fp, "retired_id": rid})
            continue
        retained.append(row)

    digests = [_sha(r) for r in retained]
    after = header + b"".join(retained)
    return {
        "_why": [
            "THE ONE WAY metadata.csv MAY CHANGE IN A PRESERVED PUBLISH (#1319).",
            "Produced BEFORE the operation from the frozen pre-op CSV and the "
            "committed asset-collapse document. Exactly the rows named below "
            "leave; every other row survives byte-identically and in order.",
            "The published CSV is not regenerated from the profile's source-path "
            "map: its file_path column already holds DESTINATION paths, so the "
            "regeneration matched 0 rows and wrote a header-only file.",
        ],
        "kind": TRANSFORM_KIND,
        "version": TRANSFORM_VERSION,
        "site": str(_resolved(site)) if site is not None else "",
        "csv": CSV_NAME,
        "original": {
            "sha256": _sha(blob),
            "bytes": len(blob),
            "data_rows": len(rows),
        },
        "header": {
            "fields": fields,
            "field_count": len(fields),
            "sha256": _sha(header),
        },
        "removals": sorted(removed, key=lambda r: r[FILE_PATH_COLUMN]),
        "expected": {
            "sha256": _sha(after),
            "bytes": len(after),
            "data_rows": len(retained),
            "ordered_digest": ordered_digest(digests),
            "row_digests": digests,
        },
    }


def _require(cond: bool, source: str, msg: str) -> None:
    if not cond:
        raise PreservedError(f"{source}: {msg}")


def _hexish(v) -> bool:
    return (isinstance(v, str) and len(v) == _SHA256_HEX
            and all(c in "0123456789abcdef" for c in v))


def parse_csv_transform(data, *, source: str) -> dict:
    """Validate a transform document, fail closed."""
    _require(isinstance(data, dict), source, "expected an object")
    _require(data.get("kind") == TRANSFORM_KIND, source,
             f"kind is {data.get('kind')!r}, not {TRANSFORM_KIND!r}")
    _require(data.get("version") == TRANSFORM_VERSION, source,
             f"version is {data.get('version')!r}, not {TRANSFORM_VERSION}")
    for section, keys in (("original", ("sha256", "bytes", "data_rows")),
                          ("header", ("fields", "field_count", "sha256")),
                          ("expected", ("sha256", "bytes", "data_rows",
                                        "ordered_digest", "row_digests"))):
        blk = data.get(section)
        _require(isinstance(blk, dict), source, f"`{section}` is not an object")
        missing = [k for k in keys if k not in blk]
        _require(not missing, source, f"`{section}` is missing {missing}")
    for path in (("original", "sha256"), ("header", "sha256"),
                 ("expected", "sha256"), ("expected", "ordered_digest")):
        v = data[path[0]][path[1]]
        _require(_hexish(v), source, f"{path[0]}.{path[1]} is not a sha256: {v!r}")
    fields = data["header"]["fields"]
    _require(isinstance(fields, list) and fields
             and all(isinstance(f, str) for f in fields), source,
             "header.fields must be a non-empty list of column names")
    _require(data["header"]["field_count"] == len(fields), source,
             f"header.field_count is {data['header']['field_count']!r} but "
             f"header.fields holds {len(fields)}")
    _require(FILE_PATH_COLUMN in fields, source,
             f"header.fields has no {FILE_PATH_COLUMN!r} column")
    digests = data["expected"]["row_digests"]
    _require(isinstance(digests, list) and all(_hexish(d) for d in digests), source,
             "expected.row_digests must be a list of sha256 digests")
    _require(data["expected"]["data_rows"] == len(digests), source,
             f"expected.data_rows is {data['expected']['data_rows']!r} but "
             f"expected.row_digests holds {len(digests)}")
    _require(ordered_digest(digests) == data["expected"]["ordered_digest"], source,
             "expected.ordered_digest does not match expected.row_digests; the "
             "document disagrees with itself")
    removals = data.get("removals")
    _require(isinstance(removals, list), source, "`removals` must be a list")
    seen_fp: set[str] = set()
    seen_rid: set[str] = set()
    for i, r in enumerate(removals):
        _require(isinstance(r, dict) and set(r) == {FILE_PATH_COLUMN, "retired_id"},
                 source, f"removals[{i}] must hold exactly {FILE_PATH_COLUMN} and "
                         f"retired_id, got {sorted(r) if isinstance(r, dict) else r!r}")
        fp, rid = r[FILE_PATH_COLUMN], r["retired_id"]
        _require(isinstance(fp, str) and fp, source,
                 f"removals[{i}].{FILE_PATH_COLUMN} is empty")
        _require(isinstance(rid, str) and rid, source,
                 f"removals[{i}].retired_id is empty")
        _require(fp not in seen_fp, source, f"removals names {fp} twice")
        _require(rid not in seen_rid, source, f"removals names {rid} twice")
        seen_fp.add(fp)
        seen_rid.add(rid)
    _require(data["original"]["data_rows"]
             == data["expected"]["data_rows"] + len(removals), source,
             f"the arithmetic does not close: {data['original']['data_rows']} "
             f"original row(s) minus {len(removals)} removal(s) is not "
             f"{data['expected']['data_rows']}")
    return data


def load_csv_transform(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        raise PreservedError(f"{path}: unreadable ({e})") from e
    return parse_csv_transform(data, source=str(path))


def transform_csv(blob: bytes, doc: dict) -> tuple[bytes, list[str]]:
    """Apply the documented transform to the PRE-OPERATION bytes.

    Returns (after, refusals). A non-empty refusal list means nothing may
    be written: the input is not the file the document describes.
    """
    refusals: list[str] = []
    if _sha(blob) != doc["original"]["sha256"]:
        refusals.append(
            f"the CSV hashes {_sha(blob)[:12]}… but the transform document was "
            f"built from {doc['original']['sha256'][:12]}…. The document is not "
            f"evidence about these bytes; re-emit it from the frozen pre-op copy "
            f"rather than widening the check.")
        return b"", refusals
    header, rows = split_csv_records(blob)
    fields, idx = _file_path_index(header)
    if fields != doc["header"]["fields"]:
        refusals.append(f"the CSV header does not match the document's "
                        f"{doc['header']['field_count']} field(s)")
        return b"", refusals
    wanted = {r[FILE_PATH_COLUMN]: r["retired_id"] for r in doc["removals"]}
    retained: list[bytes] = []
    hit: set[str] = set()
    for row in rows:
        fp = record_fields(row)[idx]
        if fp in wanted:
            hit.add(fp)
            continue
        retained.append(row)
    absent = sorted(set(wanted) - hit)
    if absent:
        refusals.append(
            f"{len(absent)} documented removal(s) have no row to remove "
            f"({absent[:5]}); the file is not in the state the document describes")
        return b"", refusals
    return header + b"".join(retained), refusals


def verify_csv_transform(doc: dict, blob: bytes) -> list[str]:
    """Every way the bytes can fail to be the documented transform.

    ⛔ EVERY CHECK RUNS AND EVERY FAILURE IS REPORTED. Returning at the
    first refusal would make the second one invisible, and an operator
    who fixes one and re-runs deserves to have seen both.
    """
    refusals: list[str] = []
    exp = doc["expected"]

    if _sha(blob) == doc["original"]["sha256"] and doc["removals"]:
        refusals.append("these are still the PRE-OPERATION bytes: the documented "
                        "removals have not been applied")

    try:
        header, rows = split_csv_records(blob)
    except PreservedError as e:
        return refusals + [str(e)]

    if _sha(header) != doc["header"]["sha256"]:
        refusals.append(
            f"the header row changed: {_sha(header)[:12]}… against the documented "
            f"{doc['header']['sha256'][:12]}…. The 41-field header is part of the "
            f"published contract and a preserved publish does not rewrite it.")
    else:
        fields = record_fields(header)
        if fields != doc["header"]["fields"]:
            refusals.append(f"the header parses to {len(fields)} field(s), not the "
                            f"documented {doc['header']['field_count']}")

    if len(rows) != exp["data_rows"]:
        refusals.append(f"{len(rows)} data row(s), the document expects "
                        f"{exp['data_rows']}")

    try:
        fields = record_fields(header)
        idx = fields.index(FILE_PATH_COLUMN)
    except ValueError:
        idx = -1
    if idx >= 0:
        present = set()
        for row in rows:
            f = record_fields(row)
            if len(f) > idx:
                present.add(f[idx])
        still_here = sorted(r[FILE_PATH_COLUMN] for r in doc["removals"]
                            if r[FILE_PATH_COLUMN] in present)
        if still_here:
            by_fp = {r[FILE_PATH_COLUMN]: r["retired_id"] for r in doc["removals"]}
            refusals.append(
                f"{len(still_here)} documented removal(s) are still in the file "
                f"({[f'{p} ({by_fp[p]})' for p in still_here[:3]]}); a removal the "
                f"document authorises and the file did not make is not a pass")

    got = [_sha(r) for r in rows]
    want = list(exp["row_digests"])
    if got != want:
        if sorted(got) == sorted(want):
            first = next((i for i, (a, b) in enumerate(zip(got, want)) if a != b),
                         len(want))
            refusals.append(
                f"the retained rows are REORDERED: row {first} is not the one the "
                f"document records there, and the multiset is unchanged. Order is "
                f"part of the published artifact.")
        else:
            extra = sorted(set(got) - set(want))
            gone = sorted(set(want) - set(got))
            first = next((i for i, (a, b) in enumerate(zip(got, want)) if a != b),
                         min(len(got), len(want)))
            refusals.append(
                f"the retained rows are not the documented ones: first difference "
                f"at row {first}; {len(extra)} row(s) the document does not record "
                f"and {len(gone)} recorded row(s) absent. A retained row must "
                f"survive BYTE-IDENTICALLY; the document is not a summary of it.")

    if ordered_digest(got) != exp["ordered_digest"]:
        refusals.append(f"the ordered digest of the retained rows is "
                        f"{ordered_digest(got)[:12]}…, the document expects "
                        f"{exp['ordered_digest'][:12]}…")

    whole = _sha(blob)
    if whole != exp["sha256"]:
        refusals.append(f"the whole file hashes {whole[:12]}…, the document expects "
                        f"{exp['sha256'][:12]}… ({len(blob)} B against "
                        f"{exp['bytes']} B)")
    return refusals


def removals_from_collapse(doc) -> list[tuple[str, str]]:
    """(retired_file_path, retired_id) for every entry of a collapse
    document, whatever its evidence kind.

    A retirement deletes its produced file, so if the CSV holds a row for
    that path the row goes with it. Which rows actually exist is decided
    against the CSV in `build_csv_transform`, not here.
    """
    return [(e.retired_file_path, e.retired_id) for e in doc.entries]


