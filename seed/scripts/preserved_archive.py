# 3. The frozen-snapshot manifest
# ---------------------------------------------------------------------------

def build_snapshot_manifest(snapshot: Path) -> dict:
    """path -> sha256 for every regular file under a frozen snapshot.

    Recorded IMMEDIATELY AFTER the snapshot is made, and kept OUTSIDE it.
    ⛔ Bytes only. Not mtime, not size, not mode: a CIFS tree can change
    under all three, and a copy that agrees with its own metadata is the
    oldest form of this mistake.
    """
    root = _resolved(snapshot)
    files = {p.relative_to(root).as_posix(): sha256_file(p)
             for p in sorted(root.rglob("*")) if p.is_file()}
    return {
        "_why": [
            "FROZEN PRE-OPERATION SNAPSHOT ATTESTATION (#1319).",
            "preserved_archive evidence is authenticated against this snapshot, "
            "and the snapshot is only trustworthy because these hashes are "
            "recomputed against it immediately before that authentication.",
            "Bytes only. Permissions and mtimes are not integrity proof.",
        ],
        "kind": SNAPSHOT_KIND,
        "snapshot": str(root),
        "files": files,
    }


def parse_snapshot_manifest(data, *, source: str) -> dict[str, str]:
    _require(isinstance(data, dict), source, "expected an object")
    _require(data.get("kind") == SNAPSHOT_KIND, source,
             f"kind is {data.get('kind')!r}, not {SNAPSHOT_KIND!r}")
    files = data.get("files")
    _require(isinstance(files, dict) and files, source,
             "`files` must be a non-empty object of path -> sha256")
    for rel, sha in files.items():
        _require(isinstance(rel, str) and rel, source, "a manifest key is empty")
        _require(_hexish(sha), source, f"files[{rel!r}] is not a sha256: {sha!r}")
    return dict(files)


def load_snapshot_manifest(path: Path) -> dict[str, str]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        raise PreservedError(f"{path}: unreadable ({e})") from e
    return parse_snapshot_manifest(data, source=str(path))


def recompute_snapshot(snapshot: Path, manifest: Mapping[str, str],
                       rels: Iterable[str]) -> list[str]:
    """RE-HASH the snapshot paths a preserved authentication is about to
    read, and compare them against the external manifest.

    ⛔ THIS IS THE WHOLE OF WHY `preserved_archive` IS EVIDENCE AT ALL. The
    snapshot is a copy we took; the manifest is what we said it was at the
    moment we took it. Without this step the authentication would be the
    archive agreeing with itself, which a stale copy does perfectly.

    Returns refusals. An empty list means every named path is present and
    still exactly the bytes the manifest attests.
    """
    root = _resolved(snapshot)
    refusals: list[str] = []
    for rel in sorted(set(rels)):
        want = manifest.get(rel)
        if want is None:
            refusals.append(
                f"{rel} is not in the snapshot manifest, so nothing attests it. "
                f"An unattested path cannot authenticate a preserved retirement.")
            continue
        p = root / rel
        if not p.is_file():
            refusals.append(f"{rel} is in the manifest but absent from the "
                            f"snapshot at {root}")
            continue
        got = sha256_file(p)
        if got != want:
            refusals.append(
                f"{rel} hashes {got[:12]}… but the manifest recorded "
                f"{want[:12]}…. The snapshot CHANGED after it was attested, so it "
                f"is not frozen and cannot authenticate anything. Permissions and "
                f"mtimes say nothing about this.")
    return refusals


