// Brush-pack registry — keyed by pack id. Phase 1.21b ships one
// built-in pack with a single procedurally-generated soft-round
// tip stamp, just enough to prove the stamp renderer works without
// committing PNGs yet. Phase 1.21c wires real ABR uploads; 1.21e
// replaces the procedural built-ins with a curated stamp pack
// shipped as static assets.
//
// The registry is module-scope so every WhiteboardSession in the
// tab shares the same pack catalogue + tinted-stamp cache. That
// matters for memory: if a user has two whiteboards open with the
// same brush, we only hold one copy of the bitmap + one copy of
// each (stamp, color) tinted surface in RAM.

import type { BrushPack, BrushStamp } from './types';

// ── Built-in soft round (procedurally generated) ─────────────────
//
// Phase 1.21b ship-it stamp: a 256-px soft-round alpha mask
// generated by drawing a radial gradient on an offscreen canvas.
// Looks like Photoshop's "Soft Round" default brush. Cached as
// an HTMLImageElement so the renderer can drawImage() it directly.
//
// We generate at module load (idempotent — once per page). Browsers
// cache the resulting image in memory; the data: URL never goes
// over the wire.

function makeSoftRoundStamp(size = 256, hardness = 0.6): HTMLImageElement {
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d')!;
  // Radial gradient from white at center to transparent at edge.
  // `hardness` (0..1) is where the edge falloff starts: 0 = pure
  // soft (Gaussian-ish), 1 = pure hard (no falloff). Photoshop's
  // hardness slider does the same thing.
  const r = size / 2;
  const g = ctx.createRadialGradient(r, r, 0, r, r, r);
  g.addColorStop(0, 'rgba(255,255,255,1)');
  g.addColorStop(hardness, 'rgba(255,255,255,1)');
  g.addColorStop(1, 'rgba(255,255,255,0)');
  ctx.fillStyle = g;
  ctx.fillRect(0, 0, size, size);
  const img = new Image();
  img.src = canvas.toDataURL('image/png');
  return img;
}

function makeHardRoundStamp(size = 256): HTMLImageElement {
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d')!;
  const r = size / 2;
  // Crisp circle with a 1-px anti-aliased edge — equivalent to
  // Photoshop's "Hard Round" with hardness 100%.
  ctx.fillStyle = '#fff';
  ctx.beginPath();
  ctx.arc(r, r, r - 0.5, 0, Math.PI * 2);
  ctx.fill();
  const img = new Image();
  img.src = canvas.toDataURL('image/png');
  return img;
}

// ── Procedural built-ins philosophy ──────────────────────────────
//
// We ship only TWO procedural stamps as always-available defaults:
// soft round + hard round. They're the universal baseline every
// raster paint tool has, and procedural code can render them
// well — they're just circles. We tried adding procedural
// charcoal / pencil / spray / calligraphy in iter1-3 of Phase 1.21e
// and they read as "tiled noise pattern stamped along a path" no
// matter how the per-stamp bitmap was tuned, because the renderer
// uses the same bitmap at every position.
//
// Real texture brushes need either per-stamp variation (each
// position generates a fresh stamp) or hand-authored stamp packs
// from an actual artist. Neither is the work of an afternoon.
// Until we build that, we hand the textured-brush story to the
// user-import flow: drop in a .abr pack of any artist's brushes
// (Kyle T. Webster, Frenden, etc — countless free + commercial
// packs exist). The Import .abr… button in the panel covers it.

const builtinPack: BrushPack = {
  id: 'builtin',
  name: 'Built-in',
  stamps: [
    {
      id: 'builtin:soft-round',
      label: 'Soft round',
      source: makeSoftRoundStamp(256, 0.4),
      // Dense spacing for a smooth stroke (10% of diameter — GIMP /
      // Photoshop default for "smooth" pen brushes).
      spacing: 0.1,
      alignToPath: false,
      // Low flow so the soft gradient mask actually reads as soft:
      // overlapping stamps at 90% overlap build the stroke up
      // smoothly instead of saturating to solid on the first pass.
      flow: 0.15,
    },
    {
      id: 'builtin:hard-round',
      label: 'Hard round',
      source: makeHardRoundStamp(256),
      spacing: 0.1,
      alignToPath: false,
      // Hard round runs at full flow so adjacent stamps overwrite
      // cleanly into a crisp solid line.
      flow: 1,
    },
  ],
};

// ── Registry ─────────────────────────────────────────────────────

const packs = new Map<string, BrushPack>();
packs.set(builtinPack.id, builtinPack);

const stampsById = new Map<string, BrushStamp>();
for (const s of builtinPack.stamps) stampsById.set(s.id, s);

export function getBrushPack(id: string): BrushPack | undefined {
  return packs.get(id);
}

export function listBrushPacks(): BrushPack[] {
  return Array.from(packs.values());
}

export function getStamp(id: string): BrushStamp | undefined {
  return stampsById.get(id);
}

export function registerPack(pack: BrushPack) {
  packs.set(pack.id, pack);
  for (const s of pack.stamps) stampsById.set(s.id, s);
  notifyChange();
}

/** Drop a pack + its stamps. Doesn't touch the tint cache — entries
 *  for the removed stamps just sit until LRU evicts them; that's
 *  cheap (a few hundred KB) and avoids a per-key scan on delete. */
export function unregisterPack(packId: string) {
  const pack = packs.get(packId);
  if (!pack) return;
  for (const s of pack.stamps) stampsById.delete(s.id);
  packs.delete(packId);
  notifyChange();
}

// ── Change-notify (let UI re-render when packs come / go) ────────
// The panel renders `listBrushPacks()` directly; without an external
// signal it can't tell the list changed when an import lands. Tiny
// subscribe API — no full reactive runtime needed, just a pub-sub.

type Listener = () => void;
const listeners = new Set<Listener>();

export function subscribeBrushPacks(l: Listener): () => void {
  listeners.add(l);
  return () => listeners.delete(l);
}
function notifyChange() {
  for (const l of listeners) l();
}

// ── API-shaped pack helper (Phase 1.21d) ─────────────────────────
//
// Convert a `{packId, stamps[]}` JSON blob from /brush-packs into a
// `BrushPack` whose stamps' `source` is a URL string pointing at the
// stamp-fetch endpoint. First `getTintedStamp` call kicks off the
// HTTPS GET; on load the source is replaced with the resolved Image
// and the canvas re-renders via the change-notify hook.

/** Schema-aligned shape — what the API returns (subset). Avoids a
 *  full import of the generated `schema.d.ts` (the generated types
 *  use `number` for ints but mark some fields nullable; this trims
 *  to just what we need at the registry layer). */
export interface APIStamp {
  id: string;
  label?: string | null;
  width: number;
  height: number;
  spacing: number;
  align_to_path: boolean;
  size_jitter?: number | null;
  opacity_jitter?: number | null;
  angle_jitter?: number | null;
}
export interface APIPack {
  id: string;
  name: string;
  source_file?: string | null;
  stamps: APIStamp[];
}

/** Where the frontend fetches stamp bytes from. Matches the OpenAPI
 *  `getBrushPackStamp` operation route. */
function stampURL(stampId: string): string {
  return `/api/v1/brush-packs/stamps/${stampId}`;
}

export function registerPackFromAPI(api: APIPack) {
  const pack: BrushPack = {
    id: api.id,
    name: api.name,
    stamps: api.stamps.map((s) => ({
      id: s.id,
      label: s.label ?? 'Stamp',
      // String source — getTintedStamp returns null on first call,
      // triggering the preload below to swap in a real Image.
      source: stampURL(s.id),
      spacing: s.spacing,
      alignToPath: s.align_to_path,
      sizeJitter: s.size_jitter ?? undefined,
      opacityJitter: s.opacity_jitter ?? undefined,
      angleJitter: s.angle_jitter ?? undefined,
    })),
  };
  registerPack(pack);
  // Eagerly preload each stamp so the first draw doesn't blink.
  for (const s of pack.stamps) preloadStamp(s);
}

/** Trigger an Image load for a URL-sourced stamp. Idempotent — if
 *  the stamp's source is already an HTMLImageElement, no-op. On
 *  load, replace the source + notify so any in-progress render
 *  picks up the bitmap on the next frame. */
async function preloadStamp(stamp: BrushStamp) {
  if (typeof stamp.source !== 'string') return;
  const url = stamp.source;
  try {
    // Use `fetch` (not `new Image()`) so we get explicit cookie
    // handling + visible HTTP status on failure. Owner-scoped
    // stamps 404 without the session cookie, and `new Image()` was
    // swallowing the error silently. credentials: 'include' ships
    // the cookie even if the URL were cross-origin (it isn't today,
    // but this future-proofs the deployment).
    const r = await fetch(url, { credentials: 'include' });
    if (!r.ok) {
      // eslint-disable-next-line no-console
      console.warn(`[whiteboard] stamp fetch failed: HTTP ${r.status} ${url}`);
      return;
    }
    const blob = await r.blob();
    const objectUrl = URL.createObjectURL(blob);
    const img = new Image();
    img.onload = () => {
      stamp.source = img;
      // Drop any cached tints rendered against the (null) pre-load
      // state. Keys are `${stampId}|${color}` — scan once.
      for (const k of Array.from(tintCache.keys())) {
        if (k.startsWith(stamp.id + '|')) tintCache.delete(k);
      }
      notifyChange();
      // Object URL is now redundant — the Image keeps the bitmap
      // in memory regardless. Revoke to release the blob.
      URL.revokeObjectURL(objectUrl);
    };
    img.onerror = () => {
      // eslint-disable-next-line no-console
      console.warn(`[whiteboard] stamp decode failed: ${url}`);
      URL.revokeObjectURL(objectUrl);
    };
    img.src = objectUrl;
  } catch (e) {
    // eslint-disable-next-line no-console
    console.warn(`[whiteboard] stamp preload error: ${url}`, e);
  }
}

// ── Tinted-stamp cache ───────────────────────────────────────────
//
// Brush stamps are grayscale alpha masks. To draw them in the user's
// chosen color, we composite the stamp with a solid color fill — but
// doing that per draw call would tank performance for any reasonable
// stroke (hundreds of stamps × per-frame re-render).
//
// Cache: keyed by `${stampId}|${color}` → tinted offscreen canvas.
// LRU-trimmed at TINT_CACHE_MAX entries to bound RAM (each entry is
// roughly stamp-size² × 4 bytes; for 256² stamps that's 256 KB
// per entry, so the cap at 64 = 16 MB ceiling).
//
// Cache invalidates when the user changes color or picks a new stamp.

const TINT_CACHE_MAX = 64;
interface TintEntry { canvas: HTMLCanvasElement; lastUsed: number; }
const tintCache = new Map<string, TintEntry>();
let tintTick = 0;

export function getTintedStamp(stamp: BrushStamp, color: string): HTMLCanvasElement | null {
  const key = `${stamp.id}|${color}`;
  const hit = tintCache.get(key);
  if (hit) {
    hit.lastUsed = ++tintTick;
    return hit.canvas;
  }
  // Source must be loaded — for <img> we need img.complete.
  const src = stamp.source;
  let w: number, h: number;
  let drawable: CanvasImageSource;
  if (src instanceof HTMLImageElement) {
    if (!src.complete || src.naturalWidth === 0) return null;
    w = src.naturalWidth;
    h = src.naturalHeight;
    drawable = src;
  } else {
    // String URL — pre-load isn't done yet. Kick one off so a click
    // on a stamp the user just imported still resolves even if the
    // registerPackFromAPI path's eager preload was missed (e.g. HMR
    // dropped the pending load mid-flight). Returns null this call;
    // notifyChange will trigger a re-render once the load completes.
    void preloadStamp(stamp);
    return null;
  }
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d')!;
  // 1. Lay down the alpha-mask stamp.
  ctx.drawImage(drawable, 0, 0);
  // 2. Replace its color with the user's color using `source-in` —
  //    keeps the existing alpha + tints the RGB.
  ctx.globalCompositeOperation = 'source-in';
  ctx.fillStyle = color;
  ctx.fillRect(0, 0, w, h);
  // Insert + trim cache.
  tintCache.set(key, { canvas, lastUsed: ++tintTick });
  if (tintCache.size > TINT_CACHE_MAX) {
    // Drop the least-recently-used entry. O(n) eviction is fine at
    // n ≤ 64; not worth a heap.
    let oldestKey = '';
    let oldestTick = Infinity;
    for (const [k, v] of tintCache) {
      if (v.lastUsed < oldestTick) { oldestTick = v.lastUsed; oldestKey = k; }
    }
    if (oldestKey) tintCache.delete(oldestKey);
  }
  return canvas;
}
