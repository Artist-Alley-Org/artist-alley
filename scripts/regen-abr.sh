#!/usr/bin/env bash
# scripts/regen-abr.sh
#
# Regenerate the Go ABR parser from app/internal/abr/abr.ksy.
#
# Run after editing the ksy file. The kaitai-struct-compiler 0.10
# Go target has a quirk: it doesn't emit a `package` declaration, so
# we sed-prepend one after generation. If a newer compiler fixes
# that, drop the sed step.
#
# Requires:
#   - java (for the .jar-based compiler)
#   - kaitai-struct-compiler 0.10 on PATH OR at $KSC

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KSY="$ROOT/app/internal/abr/abr.ksy"
OUT="$ROOT/app/internal/abr"
GENERATED="$OUT/abr.go"

KSC="${KSC:-$(command -v kaitai-struct-compiler 2>/dev/null || true)}"
if [ -z "$KSC" ]; then
    echo "kaitai-struct-compiler not on PATH. Set KSC=path/to/kaitai-struct-compiler" >&2
    echo "or install from https://kaitai.io/" >&2
    exit 2
fi

echo "==> Generating Go parser from $KSY"
"$KSC" --target go --outdir "$OUT" "$KSY"

# Quirk: the 0.10 Go target omits the `package` line. Prepend it.
if ! grep -q '^package abr' "$GENERATED"; then
    echo "==> Prepending 'package abr' to $GENERATED"
    tmp="$(mktemp)"
    {
        echo "// Code generated by kaitai-struct-compiler from a .ksy source file. DO NOT EDIT."
        echo ""
        echo "package abr"
        echo ""
        # Skip the original "Code generated" line so we don't duplicate it.
        tail -n +2 "$GENERATED"
    } > "$tmp"
    mv "$tmp" "$GENERATED"
fi

echo "==> Verifying with go build"
docker run --rm -v "$ROOT/app:/src/app" -w /src/app golang:1.26 go build ./internal/abr/... >&2

echo "==> Done. Generated: $GENERATED"
