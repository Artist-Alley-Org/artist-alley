-- artist-alley schema, as sqlc sees it.
--
-- The runtime schema is created by RS's CheckDBStruct() emitter (see
-- include/database_functions.php), which produces Postgres DDL from
-- dbstruct/*.txt. This file is the *Go-side* declaration: it must
-- mirror what CheckDBStruct emits closely enough for sqlc's compile-
-- time checker to type queries correctly.
--
-- Add only the tables Go code reads or writes. Each table is a small
-- block with a comment pointing at its dbstruct counterpart.
--
-- When CheckDBStruct is retired and Go owns the schema outright, this
-- file becomes the authoritative source and goose migrations under
-- app/migrations/ take over from CheckDBStruct.

-- Asset-type lookup table. Renamed from resource_type → asset_types
-- in migration 00028. RS field names (push_metadata, colour, tab,
-- pull_images) carried forward unchanged because RS-derived data
-- still populates this table on imports.
CREATE TABLE asset_types (
    ref                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    name                VARCHAR(200),
    allowed_extensions  TEXT,
    order_by            BIGINT,
    config_options      TEXT,
    push_metadata       BIGINT,
    colour              BIGINT,
    icon                TEXT,
    tab                 BIGINT,
    pull_images         BIGINT
);

-- table_user.txt — the columns Go's auth layer reads/writes. "user" is
-- a Postgres reserved word, hence the quoting; everything else handles
-- it identically.
-- "user" mirrors RS's table; created by migration 00007 with a UNIQUE
-- index on username added in 00008.
CREATE TABLE "user" (
    ref                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    username             VARCHAR(50),
    password             VARCHAR(255),
    fullname             VARCHAR(100),
    email                VARCHAR(100),
    usergroup            BIGINT,
    last_active          TIMESTAMPTZ,
    logged_in            BIGINT,
    accepted_terms       BIGINT NOT NULL DEFAULT 0,
    account_expires      TIMESTAMPTZ,
    session              VARCHAR(50),
    password_last_change TIMESTAMPTZ,
    login_tries          BIGINT NOT NULL DEFAULT 0,
    login_last_try       TIMESTAMPTZ,
    approved             BIGINT NOT NULL DEFAULT 1,
    lang                 VARCHAR(11),
    created              TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    origin               VARCHAR(50),
    unique_hash          VARCHAR(50),
    -- migrations/00048_federation_actor_keys.sql (Phase 1.22.A).
    -- Per-user federation identity primitives. NULL when the user
    -- has not yet been initialized as a federation actor; lazy
    -- generation on first federation event involving them.
    -- Encrypted-at-rest columns use the AES-256-GCM wrapper in
    -- app/internal/atrest (master key from AA_MASTER_KEY).
    actor_uri                  TEXT  NULL,
    signing_public_key_pem     TEXT  NULL,
    signing_private_key_enc    BYTEA NULL,
    encryption_public_key      BYTEA NULL,
    encryption_private_key_enc BYTEA NULL
);

-- migrations/00008_user_username_unique.sql
CREATE UNIQUE INDEX user_username_uniq_idx ON "user" (username);

-- migrations/00048_federation_actor_keys.sql
CREATE UNIQUE INDEX user_actor_uri_idx ON "user" (actor_uri)
    WHERE actor_uri IS NOT NULL;

-- migrations/00037_admin_user_list_indexes.sql — supports the admin
