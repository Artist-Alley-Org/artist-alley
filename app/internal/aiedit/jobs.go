// toolImg2ImgConstant is duplicated from
// [comfyuimcp.ToolImg2Img] so this file doesn't import the
// provider sub-package (which would cycle). The two MUST stay in
// sync; the bridge contract uses this exact tool name.
const toolImg2ImgConstant = "img2img"

// SourceAssetFetcher is the narrow surface the job needs to fetch
// the source asset's bytes + read its current state. Wired against
// assets.Handler + storage.Service at boot.
type SourceAssetFetcher interface {
	// FetchSourceImage reads the source asset's original bytes +
	// content type. Returns ([]byte, contentType, ok, error) so the
	// caller can distinguish "no file_hash set" from "DB error".
	FetchSourceImage(ctx context.Context, id uuid.UUID) (bytes []byte, contentType string, title string, ownerUserRef *int64, ok bool, err error)
}

// DerivativeAssetWriter is the narrow surface for committing the
// generated bytes as a new asset + the lineage row. Wired against
// storage.Service + assets.Handler + the LineageStore at boot.
type DerivativeAssetWriter interface {
	// CommitDerivative streams bytes to storage, mints the asset
	// row, and inserts the creative_lineage row in one logical
	// operation. Returns the new asset id on success.
	CommitDerivative(ctx context.Context, p DerivativeCommit) (uuid.UUID, error)
}

// DerivativeCommit is the typed input for [DerivativeAssetWriter].
// Single struct rather than multiple args so the boot wire reads
// cleanly + future fields don't reshape callers.
type DerivativeCommit struct {
	SourceAssetID  uuid.UUID
	SourceTitle    string
	OwnerUserRef   *int64
	ImageBytes     []byte
	ContentType    string
	GenerationMeta map[string]any
}

// Img2ImgJobHandler implements [jobs.Handler] for the
// aiedit.img2img job type. One per app process; pure handler with
// no per-job state.
//
// The provider field is the [ImageEditProvider] interface, not a
// concrete type — boot wires *comfyuimcp.Provider; tests inject a
// stub.
type Img2ImgJobHandler struct {
	provider ImageEditProvider
	source   SourceAssetFetcher
	writer   DerivativeAssetWriter
}

// NewImg2ImgJobHandler wires the dependency graph.
func NewImg2ImgJobHandler(prov ImageEditProvider, source SourceAssetFetcher, writer DerivativeAssetWriter) *Img2ImgJobHandler {
	return &Img2ImgJobHandler{provider: prov, source: source, writer: writer}
}

// Type implements [jobs.Handler].
func (h *Img2ImgJobHandler) Type() jobs.JobType { return JobTypeImg2Img }

// Img2ImgJobResult is the JSON shape persisted as the job's result
// row. Frontend polls the job, sees this on success, navigates to
// the new asset.
type Img2ImgJobResult struct {
	DerivativeAssetID uuid.UUID `json:"derivative_asset_id"`
	SeedUsed          int64     `json:"seed_used,omitempty"`
	PromptUsed        string    `json:"prompt_used,omitempty"`
	ModelUsed         string    `json:"model_used,omitempty"`
}

// Handle implements [jobs.Handler]. Error classification:
//
//   - jobs.TerminalError wraps any cause the worker should NOT
//     retry: source asset gone, permanent provider errors,
//     malformed bridge response after multiple attempts (we wrap as
//     terminal on first hit — the upstream worker's retry policy
//     handles re-queue elsewhere if appropriate).
//   - Plain errors stay transient and the worker retries per its
//     standard backoff.
//
// Auth: the dispatcher's capability + audit gate require an
// auth.Identity in the context. The payload carried a snapshot of
// the caller's caps at submit time — we rebuild the Identity from
// that snapshot and inject it via comfyuimcp.WithCaller so the
// dispatcher sees the same caller that submitted the request.
func (h *Img2ImgJobHandler) Handle(ctx context.Context, job *jobs.Claim) (json.RawMessage, error) {
	var p Img2ImgPayload
	if err := json.Unmarshal(job.Payload, &p); err != nil {
		return nil, &jobs.TerminalError{Err: fmt.Errorf("aiedit.img2img: parse payload: %w", err)}
	}

	// 1. Fetch source bytes.
	srcBytes, srcType, srcTitle, ownerRef, ok, err := h.source.FetchSourceImage(ctx, p.SourceAssetID)
	if err != nil {
		return nil, fmt.Errorf("aiedit.img2img: fetch source: %w", err)
	}
	if !ok {
		return nil, &jobs.TerminalError{Err: fmt.Errorf("aiedit.img2img: source asset %s gone before job ran", p.SourceAssetID)}
	}

	// 2. Re-build caller identity from the payload snapshot + plant
	// it in the context for the dispatcher gate.
	caller := &auth.Identity{
		UserRef:      p.CallerUserRef,
		AuthMethod:   "job",
		Capabilities: p.CallerCaps,
	}
	ctx = auth.WithIdentity(ctx, caller)
	ctx = WithCaller(ctx, caller)
	ctx = WithSensitivity(ctx, ai.SensitivityTier(p.Sensitivity))

	// 3. Invoke the provider. The provider was constructed with the
	// payload's ServerName (boot wire reads sysconfig at startup +
	// re-reads via the SysconfigImageEditServer adapter). Per the
	// dispatcher contract:
	//
	//   - ErrPrivacyBlocked / ErrBudgetExhausted / ErrMissing*
	//     are terminal — same job re-running won't change the
	//     gate verdict.
	//   - ErrBridgeResponseMalformed is transient — bridge may
	//     have been mid-upgrade.
	//   - Other dispatcher errors classify via the existing
	//     mcpdispatch error set.
	result, err := h.provider.Img2Img(ctx, Img2ImgRequest{
		SourceAssetID:     p.SourceAssetID,
		SourceImageBytes:  srcBytes,
		SourceContentType: srcType,
		Prompt:            p.Prompt,
		DenoiseStrength:   p.DenoiseStrength,
		Steps:             p.Steps,
		Seed:              p.Seed,
	})
	if err != nil {
		switch {
		case errors.Is(err, mcpdispatch.ErrPrivacyBlocked),
			errors.Is(err, mcpdispatch.ErrBudgetExhausted),
			errors.Is(err, mcpdispatch.ErrMissingCapability),
			errors.Is(err, mcpdispatch.ErrToolNotWhitelisted),
			errors.Is(err, mcpdispatch.ErrToolDisabled),
			errors.Is(err, mcpdispatch.ErrServerDisabled),
			errors.Is(err, ErrServerNotConfigured):
			return nil, &jobs.TerminalError{Err: fmt.Errorf("aiedit.img2img: gate: %w", err)}
		}
		// Everything else (transient provider, malformed response,
		// network) stays retriable.
		return nil, fmt.Errorf("aiedit.img2img: invoke: %w", err)
	}

	// 4. Mint the derivative asset + lineage row.
	meta := map[string]any{
		"provider":        h.provider.Name(),
		"mcp_server_name": p.ServerName,
		"mcp_tool":        toolImg2ImgConstant,
		"prompt":          p.Prompt,
		"submitted_seed":  p.Seed,
		"submitted_steps": p.Steps,
		"submitted_dn":    p.DenoiseStrength,
	}
	if result.SeedUsed != 0 {
		meta["seed_used"] = result.SeedUsed
	}
	if result.PromptUsed != "" {
		meta["prompt_used"] = result.PromptUsed
	}
	if result.ModelUsed != "" {
		meta["model_used"] = result.ModelUsed
	}
	// Merge provider-specific knobs last so they override our
	// typed fields on key conflict (provider knows best).
	for k, v := range result.GenerationMetadata {
		meta[k] = v
	}

	derivID, err := h.writer.CommitDerivative(ctx, DerivativeCommit{
		SourceAssetID:  p.SourceAssetID,
		SourceTitle:    srcTitle,
		OwnerUserRef:   ownerRef,
		ImageBytes:     result.ImageBytes,
		ContentType:    result.ContentType,
		GenerationMeta: meta,
	})
	if err != nil {
		// Commit failure is genuinely retriable — bridge already
		// did the expensive work, retry just re-attempts the
		// storage + DB write.
		return nil, fmt.Errorf("aiedit.img2img: commit derivative: %w", err)
	}

	out := Img2ImgJobResult{
		DerivativeAssetID: derivID,
		SeedUsed:          result.SeedUsed,
		PromptUsed:        result.PromptUsed,
		ModelUsed:         result.ModelUsed,
	}
	return json.Marshal(out)
}

// Compile-time assertion.
var _ jobs.Handler = (*Img2ImgJobHandler)(nil)

