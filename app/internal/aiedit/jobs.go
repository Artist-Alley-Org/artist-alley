//
// The boot wire constructs one of these; tests inject a stub that
// records the calls.

// DefaultDerivativeWriter is the production [DerivativeAssetWriter].
// Owns the storage upload + asset insert + lineage insert flow.
//
// Inserts the asset + lineage rows via direct tx SQL (not the
// LineageStore) so both writes share one transaction — splitting
// them would let a derivative survive a lineage write failure +
// vice versa, leaving asset rows without provenance.
type DefaultDerivativeWriter struct {
	storageSvc *storage.Service
	pool       *pgxpool.Pool
}

// NewDefaultDerivativeWriter wires the writer.
func NewDefaultDerivativeWriter(svc *storage.Service, pool *pgxpool.Pool) *DefaultDerivativeWriter {
	return &DefaultDerivativeWriter{storageSvc: svc, pool: pool}
}

// CommitDerivative streams the bytes through the canonical upload
// pipeline, inserts the asset row, and writes the lineage link.
// Insert + lineage live in one tx so a failure mid-flow doesn't
// leave a derivative asset without a lineage row.
func (w *DefaultDerivativeWriter) CommitDerivative(ctx context.Context, p DerivativeCommit) (uuid.UUID, error) {
	pin := storage.PinRef{SubjectType: storage.PinSubjectTypeUser}
	if p.OwnerUserRef != nil {
		pin.SubjectID = formatUserRef(*p.OwnerUserRef)
	} else {
		pin.SubjectID = "system"
	}

	// 1. Upload via the canonical pipeline (hashing + dedup + pin
	// counting + GC).
	up, err := w.storageSvc.UploadOriginal(ctx, bytesReader(p.ImageBytes), p.ContentType, pin)
	if err != nil {
		return uuid.Nil, fmt.Errorf("aiedit.commit: upload: %w", err)
	}

	// 2. Mint the asset row + lineage row in one tx.
	id := uuid.New()
	tx, err := w.pool.Begin(ctx)
	if err != nil {
		return uuid.Nil, fmt.Errorf("aiedit.commit: begin: %w", err)
	}
	defer tx.Rollback(ctx) //nolint:errcheck

	title := derivativeTitle(p.SourceTitle)
	hash := up.Hash
	ext := contentTypeToExt(p.ContentType)
	size := int64(len(p.ImageBytes))
	metaJSON := []byte(`{}`)

	_, err = tx.Exec(ctx, `
		INSERT INTO assets (
			id, title, description, asset_type, owner_user_ref,
			status, file_hash, file_extension, file_size_bytes,
			metadata, processing_status, sensitivity
		) VALUES (
			$1, $2, '', 1, $3,
			'active', $4, $5, $6,
			$7::jsonb, 'ready', 'public'
		)
	`, id, title, p.OwnerUserRef, hash, ext, size, metaJSON)
	if err != nil {
		return uuid.Nil, fmt.Errorf("aiedit.commit: insert asset: %w", err)
	}

	// 3. Lineage row — same tx so a partial commit doesn't leave a
	// derivative without provenance.
	metaJSONBytes, err := json.Marshal(p.GenerationMeta)
	if err != nil {
		return uuid.Nil, fmt.Errorf("aiedit.commit: marshal lineage meta: %w", err)
	}
	_, err = tx.Exec(ctx, `
		INSERT INTO creative_lineage (
			derivative_asset_id, source_asset_id, generation_metadata
		) VALUES ($1, $2, $3::jsonb)
	`, id, p.SourceAssetID, metaJSONBytes)
	if err != nil {
		return uuid.Nil, fmt.Errorf("aiedit.commit: insert lineage: %w", err)
	}

	if err := tx.Commit(ctx); err != nil {
		return uuid.Nil, fmt.Errorf("aiedit.commit: commit: %w", err)
	}

	// 4. Pin the new asset against the file hash. Failure here is
	// soft — the asset still works (the user pin from the upload
	// step keeps the object alive); a future GC sweep would catch
	// a missing asset pin.
	// "asset" is the storage-pin subject-type the assets package
	// uses (see assets.PinSubjectTypeAsset). Repeating the literal
	// here rather than importing the assets package keeps this
	// file's import set narrow.
	if err := w.storageSvc.AddPin(ctx, storage.PinRef{
		SubjectType: "asset",
		SubjectID:   id.String(),
	}, hash); err != nil {
		// Don't fail the job for a pin-bookkeeping error — log
		// upstream once we wire a logger in.
		_ = err
	}

	return id, nil
}

// derivativeTitle composes the new asset's title from the source
// title. "Untitled" handles sources with no title set.
func derivativeTitle(sourceTitle string) string {
	t := strings.TrimSpace(sourceTitle)
	if t == "" {
		t = "Untitled"
	}
	return "AI variation of " + t
}

// contentTypeToExt maps the bridge's MIME type to the file
// extension AA stores. Best-effort — unknown types default to
// "png" because that's what every ComfyUI workflow we ship returns.
func contentTypeToExt(ct string) *string {
	switch ct {
	case "image/png", "":
		s := "png"
		return &s
	case "image/jpeg":
		s := "jpg"
		return &s
	case "image/webp":
		s := "webp"
		return &s
	}
	s := "png"
	return &s
}

func formatUserRef(u int64) string {
	// strconv would be cleaner but pulling a stdlib import for one
	// call site is overkill; fmt.Sprintf folds inline.
	return fmt.Sprintf("%d", u)
}

// bytesReader wraps a []byte in an io.Reader so storage.Service
// can stream it.
func bytesReader(b []byte) io.Reader {
	return strings.NewReader(string(b))
}
