// Compile-time assertions.
var _ aiedit.ImageEditProvider = (*Provider)(nil)

// ---------------------------------------------------------------------------
// Response decoding
// ---------------------------------------------------------------------------

// toolsCallResult mirrors the MCP-spec tools/call result envelope.
// We only deserialize the fields we need — extra keys (e.g. isError)
// are tolerated to forward-compat with bridge upgrades.
type toolsCallResult struct {
	Content []contentItem `json:"content"`
}

// contentItem is one entry in the content array. Type discriminates
// the payload shape: "image" carries base64 + mimeType; "text"
// carries text (JSON-encoded metadata in our contract).
type contentItem struct {
	Type     string `json:"type"`
	Text     string `json:"text,omitempty"`
	Data     string `json:"data,omitempty"`
	MimeType string `json:"mimeType,omitempty"`
}

// decodeImg2ImgResponse parses the bridge response. Returns
// [aiedit.ErrBridgeResponseMalformed] when the contract isn't
// satisfied; the job layer maps that to a transient retry because
// bridges sometimes ship upgrades mid-call and a single bad
// response shouldn't fail a job permanently.
func decodeImg2ImgResponse(raw json.RawMessage) (aiedit.Img2ImgResult, error) {
	var env toolsCallResult
	if err := json.Unmarshal(raw, &env); err != nil {
		return aiedit.Img2ImgResult{}, fmt.Errorf("%w: %v", aiedit.ErrBridgeResponseMalformed, err)
	}
	if len(env.Content) == 0 {
		return aiedit.Img2ImgResult{}, fmt.Errorf("%w: empty content array", aiedit.ErrBridgeResponseMalformed)
	}

	var (
		imageBytes []byte
		mimeType   string
		metaText   string
	)
	for _, item := range env.Content {
		switch item.Type {
		case "image":
			if imageBytes != nil {
				// Multiple images in one response not supported in
				// v1 — first wins; rest ignored. E-2 variations op
				// will introduce a separate code path for fan-out.
				continue
			}
			b, err := base64.StdEncoding.DecodeString(item.Data)
			if err != nil {
				return aiedit.Img2ImgResult{}, fmt.Errorf("%w: base64 decode: %v", aiedit.ErrBridgeResponseMalformed, err)
			}
			imageBytes = b
			mimeType = item.MimeType
			if mimeType == "" {
				mimeType = "image/png"
			}
		case "text":
			if metaText == "" {
				metaText = item.Text
			}
		}
	}
	if imageBytes == nil {
		return aiedit.Img2ImgResult{}, fmt.Errorf("%w: no image content part", aiedit.ErrBridgeResponseMalformed)
	}

	out := aiedit.Img2ImgResult{
		ImageBytes:  imageBytes,
		ContentType: mimeType,
	}

	// Metadata is best-effort — a bridge that omits it loses
	// reproducibility info but doesn't fail the call. The lineage
	// row still gets the typed fields the provider knows about.
	if metaText != "" {
		var meta map[string]any
		if err := json.Unmarshal([]byte(metaText), &meta); err == nil {
			out.GenerationMetadata = meta
			if v, ok := meta["seed_used"].(float64); ok {
				out.SeedUsed = int64(v)
			}
			if v, ok := meta["prompt"].(string); ok {
				out.PromptUsed = v
			}
			if v, ok := meta["model"].(string); ok {
				out.ModelUsed = v
			}
		}
	}

	return out, nil
}

// ---------------------------------------------------------------------------
// Context plumbing — caller identity + asset sensitivity ride the
// context so the provider doesn't need a wider request shape.
// ---------------------------------------------------------------------------

// callerCtxKey + sensitivityCtxKey are unexported so external
// callers can't accidentally collide; the handler sets them via
// WithCaller / WithSensitivity below.
type callerCtxKeyT struct{}
type sensitivityCtxKeyT struct{}

var callerCtxKey callerCtxKeyT
var sensitivityCtxKey sensitivityCtxKeyT

// WithCaller attaches the calling identity to ctx. The provider
// forwards it to [mcpdispatch.InvokeOpts.Caller] for the cap gate.
func WithCaller(ctx context.Context, id *auth.Identity) context.Context {
	return context.WithValue(ctx, callerCtxKey, id)
}

// WithSensitivity attaches the source asset's sensitivity tier so
// the dispatcher's privacy gate can clamp restricted/embargo bytes
// to local-only MCP servers.
func WithSensitivity(ctx context.Context, tier ai.SensitivityTier) context.Context {
	return context.WithValue(ctx, sensitivityCtxKey, tier)
}

func callerFromContext(ctx context.Context) *auth.Identity {
	v := ctx.Value(callerCtxKey)
	id, _ := v.(*auth.Identity)
	return id
}

func sensitivityFromContext(ctx context.Context) ai.SensitivityTier {
	v := ctx.Value(sensitivityCtxKey)
	tier, _ := v.(ai.SensitivityTier)
	return tier
}

// Static guards so the unused-uuid import doesn't drift if a future
// refactor drops the asset ID forwarding.
var _ = uuid.Nil
