// Package comfyuimcp is the ComfyUI-via-MCP implementation of
// [aiedit.ImageEditProvider]. It does NOT speak to ComfyUI directly
// — the operator runs a thin Python bridge (see
// tools/comfyui-mcp-bridge/) that translates MCP tools/call
// invocations into ComfyUI workflow runs. From AA's perspective
// this is just another MCP server registered through Phase 1.53.A's
// admin UI, and the only thing the Go side cares about is the
// JSON-RPC contract the bridge exposes.
//
// # Locked contract (matches docs/operator/comfyui-mcp-bridge-setup.md)
//
// Bridge advertises an "img2img" tool via tools/list with input
// schema {prompt, source_image_url, denoise_strength, steps, seed}.
//
// Bridge's tools/call response carries an MCP-spec content array:
//
//	{
//	  "content": [
//	    {"type": "image", "data": "<base64-png>", "mimeType": "image/png"},
//	    {"type": "text",  "text": "{\"prompt\":\"...\",\"seed_used\":42,...}"}
//	  ]
//	}
//
// The provider decodes content[image] as the generated bytes and
// parses content[text].text as JSON metadata for the lineage row.
// Order within the array is irrelevant; the provider scans for the
// first matching type of each.
//
// # Why we wrap mcpdispatch, not the raw provider
//
// mcpdispatch.Dispatcher.Invoke runs the 6-step guard chain
// (capability → tool whitelist → privacy → budget → invoke → audit).
// Bypassing it would re-invent every gate.

package comfyuimcp

import (
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"

	"github.com/google/uuid"

	"github.com/mscrnt/artist-alley/app/internal/ai"
	mcpdispatch "github.com/mscrnt/artist-alley/app/internal/ai/mcp_dispatch"
	"github.com/mscrnt/artist-alley/app/internal/aiedit"
	"github.com/mscrnt/artist-alley/app/internal/auth"
)

// Name is the stable provider identifier recorded in audit rows.
const Name = "comfyuimcp"

// ToolImg2Img is the canonical tool name the bridge advertises.
// Operator-side this MUST match the per-server tool whitelist entry
// at /admin/ai/mcp-clients/{id}/tools — case-sensitive.
const ToolImg2Img = "img2img"

// Dispatcher is the narrow surface this provider needs from
// mcpdispatch.Dispatcher. *mcpdispatch.Dispatcher satisfies it;
// tests pass an in-memory stub.
type Dispatcher interface {
	Invoke(ctx context.Context, opts mcpdispatch.InvokeOpts) (json.RawMessage, error)
}

// Provider is the ComfyUI-via-MCP ImageEditProvider.
//
// Construction wires the dispatcher + the operator-configured server
// name. The provider re-reads neither across calls — operators who
// re-point at a different MCP server need a process restart (same
// shape as the rest of the AI provider registry in 1.14.A).
type Provider struct {
	disp       Dispatcher
	serverName string
}

// NewProvider builds the provider. serverName is the operator-set
// MCP registration name (e.g. "comfyui-lan"); when empty the
// provider returns aiedit.ErrServerNotConfigured from every op.
func NewProvider(disp Dispatcher, serverName string) *Provider {
	return &Provider{disp: disp, serverName: serverName}
}

// Name implements [aiedit.ImageEditProvider].
func (p *Provider) Name() string { return Name }

// Capabilities implements [aiedit.ImageEditProvider]. E-1 ships only
// Img2Img; E-2 flips the other four as their bridge sides ship.
func (p *Provider) Capabilities() aiedit.Capabilities {
	return aiedit.Capabilities{Img2Img: true}
}

// Img2Img dispatches the operator-whitelisted img2img tool against
// the configured MCP server, decodes the bridge response, and
// returns the typed result the caller writes to the lineage row +
// the storage layer.
func (p *Provider) Img2Img(ctx context.Context, req aiedit.Img2ImgRequest) (aiedit.Img2ImgResult, error) {
	if p.serverName == "" {
		return aiedit.Img2ImgResult{}, aiedit.ErrServerNotConfigured
	}

	args := map[string]any{
		"prompt":           req.Prompt,
		"source_image_url": req.SourceImageURL,
	}
	// Zero-value knobs let the bridge apply its default; only forward
	// non-zero values so operator-configured workflow defaults
	// (denoise_strength 0.7, steps 20) stay authoritative when the
	// caller didn't override.
	if req.DenoiseStrength > 0 {
		args["denoise_strength"] = req.DenoiseStrength
	}
	if req.Steps > 0 {
		args["steps"] = req.Steps
	}
	if req.Seed != 0 {
		args["seed"] = req.Seed
	}

	raw, err := p.disp.Invoke(ctx, mcpdispatch.InvokeOpts{
		ServerName:  p.serverName,
		Tool:        ToolImg2Img,
		Arguments:   args,
		Caller:      callerFromContext(ctx),
		Sensitivity: sensitivityFromContext(ctx),
		AssetID:     req.SourceAssetID,
	})
	if err != nil {
		return aiedit.Img2ImgResult{}, err
	}

	return decodeImg2ImgResponse(raw)
}

